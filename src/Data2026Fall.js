/** 위 범위를 평일 하루 단위 행으로 펼칩니다. */
function expandFall2026Calendar() {
  var out = [];
  FALL2026_CALENDAR.forEach(function (r) {
    for (var d = parseKst(r[0] + ' 00:00'); formatKst(d).slice(0, 10) <= r[1]; d = new Date(d.getTime() + 86400000)) {
      var day = formatKst(d).slice(0, 10), wd = weekdayOf(day);
      if (wd !== '토' && wd !== '일') out.push([day, r[2], r[3]]);
    }
  });
  return out;
}

/**
 * 26년도 2학기 근무표를 시트에 넣습니다. (Apps Script 편집기에서 setup 다음에 한 번 실행)
 * 이미 근무시간표·근무달력에 내용이 있으면 덮어쓰지 않고 멈춥니다.
 */
function importFall2026Schedule() {
  if (readRows_('settings').length > 0) requireAdmin_();
  return withLock_(function () {
    if (readRows_('schedule').length || readRows_('calendar').length) {
      throw new Error('근무시간표나 근무달력 탭에 이미 내용이 있습니다. 비운 뒤 다시 실행해 주세요.');
    }
    FALL2026_SCHEDULE.forEach(function (r) {
      appendRow_('schedule', { '학생이름': r[0], '이메일': '', '근무조': r[1], '팀': r[2], '요일': r[3], '시작': r[4], '종료': r[5] });
    });
    expandFall2026Calendar().forEach(function (r) {
      appendRow_('calendar', { '날짜': r[0], '근무조': r[1], '메모': r[2] });
    });
    return '근무 학생 ' + FALL2026_SCHEDULE.length + '건, 근무달력 ' + expandFall2026Calendar().length + '일을 넣었습니다.';
  });
}
